type ElementId = keyof typeof elementKinds;
type ElementFor<K extends ElementId> = InstanceType<(typeof elementKinds)[K]>;

function knownElementId(id: string): id is ElementId {
  return Object.hasOwn(elementKinds, id);
}

/** Verify the mounted DOM contract before handing elements to controllers. */
export function element<K extends ElementId>(id: K): ElementFor<K>;
export function element(id: string): HTMLElement;
export function element(id: string): HTMLElement {
  const node = document.getElementById(id);
  const kind = knownElementId(id) ? elementKinds[id] : HTMLElement;
  if (!(node instanceof HTMLElement) || !(node instanceof kind)) {
    throw new Error(`The required interface element "${id}" is missing or has the wrong type.`);
  }
  return node;
}

/** Require structure-owned descendants instead of dereferencing nullable queries. */
export function requiredQuery<T extends Element>(
  root: ParentNode,
  selector: string,
  kind: new (...args: never[]) => T,
): T {
  const node = root.querySelector(selector);
  if (!(node instanceof kind)) throw new Error(`Required interface descendant not found: ${selector}`);
  return node;
}

/** Verify a structure-owned ancestor without confusing it with a descendant query. */
export function requiredClosest<T extends Element>(
  node: Element,
  selector: string,
  kind: new (...args: never[]) => T,
): T {
  const ancestor = node.closest(selector);
  if (!(ancestor instanceof kind)) throw new Error(`Required interface ancestor not found: ${selector}`);
  return ancestor;
}

/** Cancel an optional browser timer without inventing a sentinel timer ID. */
export function clearTimer(timer: number | null | undefined) {
  if (timer !== null && timer !== undefined) window.clearTimeout(timer);
}

/** Enforce a controller invariant with an actionable error instead of a null dereference. */
export function requireValue<T>(value: T, subject = "Required application state"): NonNullable<T> {
  if (value === null || value === undefined) throw new Error(`${subject} is no longer available.`);
  return value;
}

/** Enumerate only HTML controls when applying HTML-specific layout and focus properties. */
export function htmlChildren(node: Element): HTMLElement[] {
  return [...node.children].filter((child): child is HTMLElement => child instanceof HTMLElement);
}

/** Require attributes that identify a controller-owned action or resource. */
export function datasetValue(node: HTMLElement, key: string): string {
  const value = node.dataset[key];
  if (value === undefined) throw new Error(`The interface action is missing data-${key}.`);
  return value;
}

/** Narrow the resource kind carried by a file-tree action. */
export function entryKind(node: HTMLElement): "file" | "directory" {
  const kind = node.dataset.entryKind;
  if (kind !== "file" && kind !== "directory") throw new Error("The file action has no valid resource kind.");
  return kind;
}
